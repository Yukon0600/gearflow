const {test,expect}=require('@playwright/test');
test('新增员工、客户点名装机、完成计提并查看销售提成',async({page})=>{
 await page.request.post('/api/auth/login',{data:{username:'admin',password:'GearFlow@2026'}});
 await page.goto('/');await expect(page.getByText('服务器已连接')).toBeVisible();
 await page.getByRole('button',{name:'员工档案',exact:true}).first().click();
 await page.getByRole('button',{name:'新增员工',exact:true}).click();
 const code='STAFF-'+Date.now();
 await page.getByLabel('工号',{exact:true}).fill(code);
 await page.getByLabel('员工姓名',{exact:true}).fill(code);
 await page.getByRole('button',{name:'保存员工',exact:true}).click();
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(page.locator('tbody')).toContainText(code);
 await page.getByRole('button',{name:'装机服务',exact:true}).first().click();
 await page.getByRole('button',{name:'新建装机服务',exact:true}).click();
 await page.getByLabel('装机客户',{exact:true}).selectOption({index:1});
 await page.getByLabel('装机员工',{exact:true}).selectOption({label:code+' · 销售顾问'});
 await page.getByLabel('指派方式',{exact:true}).selectOption({label:'客户点名'});
 await page.getByLabel('服务项目',{exact:true}).fill(code+' 装机测试');
 await page.getByLabel('装机服务费（元）',{exact:true}).fill('200');
 await page.getByRole('button',{name:'创建装机单',exact:true}).click();
 const row=page.locator('tbody tr').filter({hasText:code});
 await expect(row).toContainText('客户点名');
 await row.getByRole('button',{name:'开始装机',exact:true}).click();
 await row.getByRole('button',{name:'确认完成',exact:true}).click();
 await expect(row).toContainText('已完成');
 await page.getByRole('button',{name:'员工提成',exact:true}).first().click();
 const commission=page.locator('tbody tr').filter({hasText:code});
 await expect(commission).toContainText('¥60.00');
 await expect(page.locator('tbody')).toContainText('销售提成');
 await page.screenshot({path:'artifacts/commissions-desktop.png',animations:'disabled'});
 await page.setViewportSize({width:390,height:844});
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
});
