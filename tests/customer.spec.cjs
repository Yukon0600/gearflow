test('编辑商品不会改库存；库存排序、分页、卡片视图和折叠导航可用',async({page})=>{
 await page.goto('/');
 await expect(page.getByText('服务器已连接')).toBeVisible();
 await page.getByRole('button',{name:'折叠侧栏',exact:true}).click();
 await expect(page.locator('.shell')).toHaveClass(/is-collapsed/);
 await page.getByRole('button',{name:'展开侧栏',exact:true}).click();
 await page.getByLabel('商品排序').selectOption('stock');
 const counts=await page.locator('.stock-cell b').allTextContents();
 expect(counts.map(Number)).toEqual(counts.map(Number).sort((a,b)=>a-b));
 await page.getByLabel('搜索商品',{exact:true}).fill('CPU-AMD-9700X');
 const row=page.locator('tbody tr');
 const stock=await row.locator('.stock-cell b').textContent();
 await row.getByRole('button',{name:'AMD Ryzen 7 9700X修改商品',exact:true}).click();
 await page.getByLabel('销售价（元）',{exact:true}).fill('2499');
 await page.getByRole('button',{name:'保存修改',exact:true}).click();
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(row.locator('.price')).toContainText('2,499');
 await expect(row.locator('.stock-cell b')).toHaveText(stock);
 await page.getByRole('button',{name:'卡片视图',exact:true}).click();
 await expect(page.locator('.catalog-card')).toHaveCount(1);
 await expect(page.locator('.catalog-card')).toContainText('AMD Ryzen 7 9700X');
 await page.getByRole('button',{name:'清除筛选',exact:true}).click();
 await expect(page.locator('.catalog-card')).toHaveCount(10);
 await page.getByRole('button',{name:'下一页',exact:true}).click();
 await expect(page.locator('.pagination b')).toContainText('2 /');
 await page.getByLabel('每页数量').selectOption('50');
 await expect(page.locator('.pagination b')).toHaveText('1 / 1');
 await page.getByRole('button',{name:'表格视图',exact:true}).click();
 await page.screenshot({path:'artifacts/workspace-refined.png',fullPage:true,animations:'disabled'});
});

