test('客户可以建立商品并完成入库、出库、库存核对和导出',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByText('服务器已连接')).toBeVisible();
 await page.screenshot({path:'artifacts/customer-desktop.png',fullPage:true,animations:'disabled'});
 const sku='TEST-'+Date.now();
 await page.getByRole('button',{name:'新建商品',exact:true}).click();
 await page.getByLabel('商品名称',{exact:true}).fill('测试装机处理器');
 await page.getByLabel('SKU 编码').fill(sku);
 await page.getByLabel('品牌',{exact:true}).fill('TEST');
 await page.getByLabel('采购参考价（元）',{exact:true}).fill('100');
 await page.getByLabel('销售价（元）',{exact:true}).fill('150');
 await page.getByRole('button',{name:'创建商品',exact:true}).click();
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await page.getByLabel('搜索商品',{exact:true}).fill(sku);
 let row=page.locator('tbody tr').filter({hasText:sku});
 await expect(row).toContainText('已缺货');
 await row.getByRole('button',{name:'测试装机处理器入库',exact:true}).click();
 await page.getByLabel('供应商名称',{exact:true}).fill('自动化测试供货商');
 await page.getByLabel('数量',{exact:true}).fill('10');
 await page.getByRole('button',{name:'确认入库',exact:true}).click();
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(row.locator('.stock-cell b')).toHaveText('10');
 await row.getByRole('button',{name:'测试装机处理器出库',exact:true}).click();
 await page.getByLabel('客户名称',{exact:true}).fill('自动化测试客户');
 await page.getByLabel('数量',{exact:true}).fill('11');
 await page.getByRole('button',{name:'确认出库',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('库存不足');
 await page.getByLabel('数量',{exact:true}).fill('3');
 await page.getByRole('button',{name:'确认出库',exact:true}).click();
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(row.locator('.stock-cell b')).toHaveText('7');
 await page.reload();
 await page.getByLabel('搜索商品',{exact:true}).fill(sku);
 await expect(page.locator('tbody tr').filter({hasText:sku}).locator('.stock-cell b')).toHaveText('7');
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'导出数据'}).click();
 expect((await download).suggestedFilename()).toBe('GearFlow-inventory.csv');
 await page.locator('nav').getByRole('button',{name:'库存流水',exact:true}).click();
 await page.getByLabel('搜索库存流水').fill(sku);
 await expect(page.locator('tbody tr')).toHaveCount(2);
 await expect(page.locator('tbody tr').first()).toContainText('-3');
 expect(errors).toEqual([]);
});
